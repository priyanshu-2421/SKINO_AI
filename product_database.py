# =========================================================
# PRODUCT FILTERING
# =========================================================

def get_products(skin_type, category="All", brand="All"):

    results = []

    for product in PRODUCTS:

        matches_skin = (
            skin_type in product["skin_types"]
        )

        matches_category = (
            category == "All"
            or product["category"] == category
        )

        matches_brand = (
            brand == "All"
            or product["brand"] == brand
        )

        if matches_skin and matches_category and matches_brand:
            results.append(product)

    return results


# =========================================================
# FILTER OPTIONS
# =========================================================

def get_categories():
    return sorted({
        product["category"]
        for product in PRODUCTS
    })


def get_brands():
    return sorted({
        product["brand"]
        for product in PRODUCTS
    })


